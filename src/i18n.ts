export type TranslationKey = keyof typeof EN_MESSAGES;
export type Translator = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function createTranslator(locale = "en"): Translator {
  const messages = isChineseLocale(locale) ? ZH_MESSAGES : EN_MESSAGES;
  return (key, vars) => formatMessage(messages[key] ?? EN_MESSAGES[key] ?? key, vars);
}

function isChineseLocale(locale: string): boolean {
  const normalized = locale.toLowerCase();
  return normalized === "zh" || normalized.startsWith("zh-cn") || normalized.startsWith("zh-hans");
}

function formatMessage(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}
